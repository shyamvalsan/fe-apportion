#!/usr/bin/env python3
"""Independent exact-rational oracle and deterministic cross-backend fixtures.

The Fe implementation repeatedly freezes one binding cap. This oracle instead
sorts rational cap/weight breakpoints, solves the continuous water level, then
rounds exact Fractions. It uses Python's unbounded integers, not u256 arithmetic.
"""
from __future__ import annotations

import argparse
from fractions import Fraction
import json
from pathlib import Path
import random
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
MAX = 2**128 - 1
SEED = 0xFEA110CA


def reference(total, weights, caps=None, rotate=0):
    assert 1 <= len(weights) <= 64
    assert 0 <= total <= MAX and all(0 <= w <= MAX for w in weights)
    caps = [total] * len(weights) if caps is None else caps
    assert len(caps) == len(weights) and all(0 <= c <= MAX for c in caps)
    n = len(weights)
    if total == 0:
        return {"shares": [0] * n, "ideal": [Fraction(0)] * n}
    positive = [i for i, w in enumerate(weights) if w]
    if not positive:
        return {"error": "NoPositiveWeight"}
    if sum(caps[i] for i in positive) < total:
        return {"error": "InsufficientCapacity"}

    order = sorted(positive, key=lambda i: (Fraction(caps[i], weights[i]), i))
    active_weight = sum(weights)
    spent = 0
    level = Fraction(0)
    for i in order:
        level = Fraction(total - spent, active_weight)
        if level <= Fraction(caps[i], weights[i]):
            break
        spent += caps[i]
        active_weight -= weights[i]
    ideal = [min(Fraction(c), level * w) for w, c in zip(weights, caps)]
    assert sum(ideal) == total
    shares = [x.numerator // x.denominator for x in ideal]
    remainder = [x - floor for x, floor in zip(ideal, shares)]
    priority = sorted(range(n), key=lambda i: (-remainder[i], (i - rotate) % n))
    for i in priority[:total - sum(shares)]:
        shares[i] += 1
    assert sum(shares) == total
    assert all(0 <= v <= c and (w > 0 or v == 0) for v, c, w in zip(shares, caps, weights))
    assert all(abs(Fraction(v) - q) < 1 or Fraction(v) == q for v, q in zip(shares, ideal))
    return {"shares": shares, "ideal": ideal}


def cases(random_count=128):
    named = [
        ("zero_total_zero_weights", 0, [0, 0, 0], [0, 0, 0], 0),
        ("all_zero_weights", 1, [0, 0, 0], [10, 10, 10], 0),
        ("capacity_excludes_zero_weight", 4, [1, 0], [3, MAX], 0),
        ("empty_capacity", 1, [1, 1], [0, 0], 0),
        ("equal_index", 10, [1, 1, 1], None, 0),
        ("equal_rotated", 10, [1, 1, 1], None, 2),
        ("offset_wraps", 10, [1, 1, 1], None, 100),
        ("exclude_zero_weights", 7, [0, 1, 0, 1], None, 0),
        ("single_recipient_max", MAX, [MAX], [MAX], 0),
        ("max_product", MAX, [MAX, MAX], None, 0),
        ("sum_weights_exceeds_u128", MAX, [MAX] * 64, None, 63),
        ("tiny_dominant_weight", 1, [MAX, 1, 1], None, 1),
        ("cap_redistributes", 100, [8, 1, 1], [40, 100, 100], 0),
        ("successive_caps", 100, [90, 9, 1], [20, 30, 100], 0),
        ("binding_exact_cap", 12, [1, 2, 3], [2, 4, 6], 0),
        ("zero_caps", 3, [9, 9, 1, 1], [0, 0, 10, 10], 3),
        ("just_below_rational_cap", 10, [5, 3, 2], [4, 100, 100], 0),
        ("rounding_reaches_cap", 2, [1, 1, 1], [1, 1, 1], 0),
        ("all_capacity_exact", MAX, [MAX, 1], [MAX - 1, 1], 0),
        ("alabama_ten", 10, [6, 6, 2], None, 0),
        ("alabama_eleven", 11, [6, 6, 2], None, 0),
        ("alabama_classic_25", 25, [1500, 1500, 900, 500, 500, 200], None, 0),
        ("alabama_classic_26", 26, [1500, 1500, 900, 500, 500, 200], None, 0),
    ]
    data = [dict(name=name, total=t, weights=w, caps=c, rotate=r) for name,t,w,c,r in named]
    rng = random.Random(SEED)
    for k in range(random_count):
        n = rng.choice([1, 2, 3, 4, 8, 16, 32, 64])
        large = k % 5 == 0
        total = rng.randrange(MAX + 1) if large else rng.randrange(5001)
        weights = [rng.randrange(MAX + 1) if large else rng.randrange(101) for _ in range(n)]
        if k % 11 == 0:
            weights[rng.randrange(n)] = 0
        caps = None if k % 3 == 0 else [rng.randrange(MAX + 1) if large else rng.randrange(5001) for _ in range(n)]
        data.append(dict(name=f"seeded_{k:03}", total=total, weights=weights, caps=caps, rotate=rng.randrange(1 << 32)))
    return data


def solved(case):
    return reference(case["total"], case["weights"], case["caps"], case["rotate"])


def serializable(case):
    result = solved(case)
    return {**case, **{k: ([str(x) for x in v] if isinstance(v, list) else v) for k,v in result.items()}}


def fe_source(data):
    lines = [
        "// Generated by tools/oracle.py from independent Python Fraction arithmetic.",
        "// Regenerate with: python3 tools/oracle.py --generate",
        "use ingot::{allocate_capped, AllocationError, TieBreak}",
        "", 
        "fn verify<const N: usize>(_ total: u128, _ weights: [u128; N], _ caps: [u128; N], _ rotate: usize, _ expected: [u128; N]) where N > 0 && N <= 64 {",
        "    let result = match allocate_capped(total, weights, caps, TieBreak::Rotate(rotate)) {",
        "        Result::Ok(value) => value",
        "        Result::Err(_) => panic()",
        "    }",
        "    var sum: u256 = 0",
        "    var i: usize = 0",
        "    while i < N {",
        "        assert!(result.shares[i] == expected[i])",
        "        assert!(result.shares[i] <= caps[i])",
        "        if weights[i] == 0 { assert!(result.shares[i] == 0) }",
        "        sum += result.shares[i] as u256",
        "        i += 1",
        "    }",
        "    assert!(sum == total as u256)",
        "}",
        "",
    ]
    for case in data:
        result = solved(case)
        c = case["caps"] if case["caps"] is not None else [case["total"]] * len(case["weights"])
        args = f'{case["total"]}, {case["weights"]}, {c}, {case["rotate"]}'
        lines += ["#[test]", f'fn oracle_{case["name"]}() {{']
        if "error" in result:
            args = f'{case["total"]}, {case["weights"]}, {c}, TieBreak::Rotate({case["rotate"]})'
            lines += [f"    match allocate_capped({args}) {{", f'        Result::Err(AllocationError::{result["error"]}) => {{}}', "        _ => panic()", "    }"]
        else:
            lines += [f'    verify({args}, {result["shares"]})']
        lines += ["}", ""]
    return "\n".join(lines)


def crosscheck(executable, data):
    for case in data:
        caps = case["caps"]
        tokens = [str(case["total"]), str(case["rotate"])]
        tokens += [str(w) if caps is None else f"{w}:{caps[i]}" for i,w in enumerate(case["weights"])]
        completed = subprocess.run([str(executable)], input=" ".join(tokens) + "\n", text=True, capture_output=True, timeout=10)
        try:
            actual = json.loads(completed.stdout)
        except json.JSONDecodeError as exc:
            raise AssertionError((case["name"], completed.returncode, completed.stdout, completed.stderr)) from exc
        expected = solved(case)
        if "error" in expected:
            assert actual == {"error": expected["error"]}, (case, actual, expected)
            assert completed.returncode == 2
        else:
            assert completed.returncode == 0, (case, completed.stderr)
            assert [int(x) for x in actual["shares"]] == expected["shares"], (case, actual, expected)
    print(f"Native CLI: {len(data)} exact-rational differential cases passed (seed {SEED:#x}).")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--generate", action="store_true")
    parser.add_argument("--check-generated", action="store_true")
    parser.add_argument("--cli", type=Path)
    parser.add_argument("--random-cases", type=int, default=1000)
    args = parser.parse_args()
    fixture_cases = cases()
    text = fe_source(fixture_cases)
    json_text = json.dumps([serializable(c) for c in fixture_cases], indent=2) + "\n"
    if args.generate:
        (ROOT / "src" / "oracle_vectors.fe").write_text(text, encoding="utf-8", newline="\n")
        (ROOT / "tests" / "vectors.json").parent.mkdir(exist_ok=True)
        (ROOT / "tests" / "vectors.json").write_text(json_text, encoding="utf-8", newline="\n")
        print(f"Generated {len(fixture_cases)} exact-rational fixtures.")
    if args.check_generated:
        # Fe's formatter inserts optional commas as well as wrapping vectors.
        # Preserve token boundaries (especially numeric literals) while ignoring
        # these cosmetic differences; JSON fixtures still match byte-for-byte.
        actual = (ROOT / "src" / "oracle_vectors.fe").read_text(encoding="utf-8")
        assert re.findall(r"\w+|[^\s,]", actual) == re.findall(r"\w+|[^\s,]", text)
        assert (ROOT / "tests" / "vectors.json").read_text(encoding="utf-8") == json_text
        print(f"Verified {len(fixture_cases)} checked-in fixtures against the oracle.")
    if args.cli:
        crosscheck(args.cli.resolve(), cases(args.random_cases))
    if not (args.generate or args.check_generated or args.cli):
        parser.print_help()


if __name__ == "__main__":
    main()
